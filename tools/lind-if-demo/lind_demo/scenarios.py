"""Editable reference sequences. The file runner accepts exactly these JSON-shaped steps."""


def step(op, **arguments):
    return dict(op=op, **arguments)


def check(path, equals):
    return step("check", path=path, equals=equals)


def scenario(description, limitations, *steps):
    return dict(description=description, limitations=limitations.split(), steps=list(steps))


